#!/usr/bin/env python3
"""generate/generate.py against an invented acme policy repo (test/generate/fixtures/policy, which carries the files the
generator writes, committed as a tenant would). Run: python3 test/generate/test_generate.py (needs pyyaml).

With REPRODUCE=<a policy checkout> and REPRODUCE_REPO=<owner/name> set, it also runs --check against that checkout:
the byte-for-byte proof that this generator reproduces a policy repo's committed files. Nothing here names one."""
import json
import traceback
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
GEN = ROOT / "generate" / "generate.py"
FIXTURE = Path(__file__).resolve().parent / "fixtures" / "policy"
failures = 0


def copy() -> Path:
    d = Path(tempfile.mkdtemp()) / "policy"
    shutil.copytree(FIXTURE, d)
    return d


def gen(d: Path, *args: str, repo: str | None = "acme/policy", env: dict | None = None):
    cmd = [sys.executable, "-I", str(GEN), "--policy", str(d), *args]
    if repo:
        cmd += ["--repo", repo]
    e = {k: v for k, v in os.environ.items() if k != "GITHUB_REPOSITORY"}
    e.update(env or {})
    return subprocess.run(cmd, capture_output=True, text=True, env=e)


def case(name: str):
    def wrap(fn):
        global failures
        try:
            fn()
            print(f"ok  {name}")
        except AssertionError as e:
            failures += 1
            line = traceback.extract_tb(e.__traceback__)[-1].lineno
            print(f"FAIL {name} (line {line}): {e}")
        return fn
    return wrap


def set_config(d: Path, edit) -> None:
    import yaml
    p = d / "config.yaml"
    cfg = yaml.safe_load(p.read_text())
    edit(cfg)
    p.write_text(yaml.safe_dump(cfg, sort_keys=False))


@case("the committed fixture is exactly what the policy produces (check passes, write changes nothing)")
def _():
    r = gen(FIXTURE, "--check")
    assert r.returncode == 0 and "OK: 0 stale file(s) of 18" in r.stdout, r.stdout + r.stderr
    d = copy()
    before = {p.relative_to(d): p.read_bytes() for p in d.rglob("*") if p.is_file()}
    r = gen(d, "--write")
    assert r.returncode == 0, r.stdout
    after = {p.relative_to(d): p.read_bytes() for p in d.rglob("*") if p.is_file()}
    assert before == after, sorted(set(before) ^ set(after)) or [k for k in before if before[k] != after[k]]


