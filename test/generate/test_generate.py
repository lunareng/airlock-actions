@case("fails closed: a bad or missing setting writes nothing and says which")
def _():
    bad = [
        ("airlock_actions.ref", lambda c: c["airlock_actions"].update(ref="main")),
        ("airlock_actions.ref", lambda c: c["airlock_actions"].update(ref="v1")),
        ("airlock_actions.ref", lambda c: c.pop("airlock_actions")),
        ("airlock_actions.note", lambda c: c["airlock_actions"].update(note="two\nlines")),
        ("role_runs.runner", lambda c: c["role_runs"].update(runner="a b")),
        ("role_runs.git_email_domain", lambda c: c["role_runs"].update(git_email_domain="not a domain")),
        ("generated.apps", lambda c: c["generated"].update(apps="../outside")),
        ("generated.codeowners", lambda c: c["generated"].update(codeowners=".github/owners")),
        ("human_owner", lambda c: c.pop("human_owner")),
        ("required_checks", lambda c: c.update(required_checks={"web": ["x"]})),
        ("clock", lambda c: c.update(clock=[{"workflow": "x.yml"}])),
        ("clock", lambda c: c["clock"][0]["inputs"].update(clock="false")),
        ("clock", lambda c: c["clock"][0]["inputs"].update(CLOCK="false")),
        ("clock", lambda c: c["clock"][0].update(cron="*/30 * * * *\n")),
        ("clock", lambda c: c["clock"][0].update(workflow="role-router.yml\n")),
        ("strict", lambda c: c.update(strict=["web\r"])),
        ("clock", lambda c: c["clock"][0].update(cron="every day")),
        ("strict", lambda c: c.update(strict="web")),
        ("required_checks.web", lambda c: c["required_checks"].update(web="build")),
        ("owner_review", lambda c: c.update(owner_review="false")),
    ]
    for key, edit in bad:
        d = copy()
        set_config(d, edit)
        shutil.rmtree(d / "generated")
        r = gen(d, "--write")
        assert r.returncode == 1 and "::error title=airlock generate::" in r.stdout and key.split(".")[0] in r.stdout, (key, r.stdout)
        assert not (d / "generated").exists(), (key, "wrote files")
    d = copy()
    (d / "repos/api.yaml").write_text((d / "repos/api.yaml").read_text().replace("default: L3", "default: L0"))
    r = gen(d, "--check")
    assert r.returncode == 1 and "level 'L0'" in r.stdout, r.stdout
    d = copy()
    (d / "roles/helper/role.yaml").write_text((d / "roles/helper/role.yaml").read_text().replace("role: helper", "role: other"))
    r = gen(d, "--check")
    assert r.returncode == 1 and "roles/helper/role.yaml" in r.stdout, r.stdout
    d = copy()
    (d / "roles/triage/role.yaml").write_text((d / "roles/triage/role.yaml").read_text().replace('  schedule: "15 9 * * 1-5"\n', ""))
    r = gen(d, "--check")
    assert r.returncode == 1 and "run.schedule" in r.stdout, r.stdout
    d = copy()
    (d / "repos/api.yaml").write_text((d / "repos/api.yaml").read_text().replace("why: Billing moves money.", 'why: "Billing.\\n* @attacker"'))
    r = gen(d, "--check")
    assert r.returncode == 1 and "src/billing/** why: must be a one-line string" in r.stdout, r.stdout
    d = copy()
    (d / "roles/triage/role.yaml").write_text((d / "roles/triage/role.yaml").read_text().replace('"15 9 * * 1-5"', '"15 9 * * 1-5\\"\\nevil: x"'))
    r = gen(d, "--check")
    assert r.returncode == 1 and "run.schedule: cron" in r.stdout, r.stdout
    d = copy()
    (d / "roles/triage/role.yaml").write_text((d / "roles/triage/role.yaml").read_text().replace('"15 9 * * 1-5"', '"15 9 * * 1-5\\n"'))
    r = gen(d, "--check")
    assert r.returncode == 1 and "run.schedule: cron" in r.stdout, ("a trailing newline too", r.stdout)
    d = copy()
    (d / "repos/api.yaml").write_text((d / "repos/api.yaml").read_text().replace('glob: "migrations/**"', 'glob: "* @attacker"'))
    r = gen(d, "--check")
    assert r.returncode == 1 and "no whitespace" in r.stdout, r.stdout
    d = copy()
    (d / "repos/api.yaml").write_text((d / "repos/api.yaml").read_text() + "  - just a string\n")
    r = gen(d, "--check")
    assert r.returncode == 1 and "paths: a list" in r.stdout, r.stdout
    d = copy()
    (d / ".github/workflows/role-other.yml").write_bytes(b"\xff\xfe not utf-8")
    r = gen(d, "--check")
    assert r.returncode == 1 and "::error title=airlock generate::" in r.stdout and "Traceback" not in r.stderr, (r.stdout, r.stderr)
    d = copy()
    (d / ".github/workflows/role-triage.yml").write_text("# Ours.\nname: triage\n")
    r = gen(d, "--write")
    assert r.returncode == 1 and "role-triage.yml is hand-written" in r.stdout, r.stdout
    assert (d / ".github/workflows/role-triage.yml").read_text() == "# Ours.\nname: triage\n"
    r = gen(FIXTURE, "--check", repo="not-a-full-name")
    assert r.returncode == 1 and "owner/name" in r.stdout, r.stdout


